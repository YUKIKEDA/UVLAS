"""Geometry-defined membrane/shear projection with raw thickness variation."""
from functools import lru_cache
import numpy as np
from scipy.linalg import svd,qr,solve
import qem_el2_q4 as base
from qem_el2_q4 import MB,C,CH,SLICES,shape,tables,raw,expansion,quadrature,mesh,displacement,target,reference_h1,boundary,native_plane,native_volume,metric_factor,solve_ball
CI=np.linalg.inv(C)
def ranks(s):return [int(np.count_nonzero(s>t*s[0])) for t in [1e-9,1e-10,1e-11]]

class PreparationFailure(ValueError):
    pass

def make_basis(q,order=9,independent=False):
    p,w=quadrature(order,2);pn,_=native_plane();_,Jn,Bn=raw(q,pn,0.,independent)
    _,J,B=raw(q,p,0.,independent);mu=w*np.linalg.det(J);mu/=mu.sum()
    if np.min(np.linalg.det(J))<=0:raise ValueError('invalid_reference_geometry')
    D=np.zeros((225,50))
    for i in range(25):D[3*i:3*i+3,2*i:2*i+2]=Jn[i,:,:2]
    n=np.cross(J[:,:,0],J[:,:,1]);n/=np.linalg.norm(n,axis=1)[:,None];Pt=np.eye(3)-n[:,:,None]*n[:,None,:]
    tangent=B@D;tensor=np.einsum('kij,pkn->pijn',MB,tangent)
    membrane=np.einsum('pai,pijn,pjb->pabn',Pt,tensor,Pt,optimize=True)
    membrane=np.einsum('kab,pabn->pkn',MB,membrane)
    N,g=shape(p,0,independent);scalar=np.zeros((len(p),25,3));scalar[:,:,:2]=g;G=scalar@np.linalg.inv(J)
    shear=np.einsum('kij,pi,pnj->pkn',MB,np.linalg.inv(J)[:,2,:],G) # Mandel(sym(n tensor grad N))
    # All actual normal-strain fields generated by transverse gradient DOFs.
    tensor_d=np.einsum('kij,pkn->pijn',MB,B[:,:,75:150]);normal_scalar=np.einsum('pi,pijn,pj->pn',n,tensor_d,n)
    nn=np.einsum('kij,pi,pj->pk',MB,n,n);normal=nn[:,:,None]*normal_scalar[:,None,:]
    Dspin=np.zeros((225,3));center=q.reshape(75,3)[:25].mean(axis=0)
    for axis_index,axis in enumerate(np.eye(3)):
        Dspin[75:150,axis_index]=np.cross(axis,q.reshape(75,3)[:25]-center).reshape(75)
    spin=B@Dspin
    A=np.concatenate((membrane,shear,normal,spin,np.broadcast_to(np.eye(6),(len(p),6,6))),axis=2)
    W=(np.einsum('ij,pjn->pin',CH,A)*np.sqrt(mu)[:,None,None]).reshape(-1,A.shape[2])
    norms=np.linalg.norm(W,axis=0);active=norms>1e-14*norms.max();normalized=W[:,active]/norms[active]
    if independent:
        sing=svd(normalized,compute_uv=False,lapack_driver='gesvd',check_finite=False)
        U,R,pivot=qr(normalized,mode='economic',pivoting=True,check_finite=False)
    else:U,sing,V=svd(normalized,full_matrices=False,check_finite=False)
    rr=ranks(sing)
    if rr!=[rr[1]]*3:raise PreparationFailure('projection_rank_uncertain:'+str(rr))
    rank=rr[1];U=U[:,:rank]
    S=np.einsum('ij,pjn->pin',np.linalg.inv(CH),U.reshape(len(p),6,rank))/np.sqrt(mu)[:,None,None]
    span=float(np.linalg.norm(W-U@(U.T@W))/np.linalg.norm(W))
    if span>1e-10:raise PreparationFailure('projection_span_failed:'+str(span))
    return dict(q=q,p=p,w=w,S=S,rank=rank,ranks=rr,span=span,singular=sing,mu0=mu,normal=n)

@lru_cache(maxsize=128)
def cached_basis(qbytes,order):return make_basis(np.frombuffer(qbytes,dtype=np.float64).copy(),order)

def prepare(q,order=9):return cached_basis(np.asarray(q,dtype=np.float64).tobytes(),order)

def measure(q,h,order=9,order_z=5):
    plane,wp=quadrature(order,2);z,wz=np.polynomial.legendre.leggauss(order_z)
    p=np.array([[s,t,c] for (s,t),c in __import__('itertools').product(plane,z)]);w=np.array([a*b for a,b in __import__('itertools').product(wp,wz)])
    _,J,_=raw(q,p,h*p[:,2]/2);mu=w*np.linalg.det(J);mu/=mu.sum()
    return p,w,J,mu,mu.reshape(len(plane),order_z).sum(axis=1)

def project_mid(state,h,E0,order_z=5):
    p,w,J,mu,plane_mu=measure(state['q'],h,int(np.sqrt(len(state['p']))),order_z);S=state['S']
    H=np.einsum('p,pki,kl,plj->ij',plane_mu,S,C,S,optimize=True)
    rhs=np.einsum('p,pki,kl,pln->in',plane_mu,S,C,E0,optimize=True)
    coeff=solve(H,rhs,assume_a='sym',check_finite=False)
    return S@coeff,mu,H

def project_fields(q,h,Eraw,Enative=None,order=9,order_z=5,conservative=True,state=None):
    state=prepare(q,order) if state is None else state
    fields=Eraw.reshape(order*order,order_z,6,-1);mid=fields[:,order_z//2]
    Pmid,mu,H=project_mid(state,h,mid,order_z)
    result=(fields-mid[:,None]+Pmid[:,None]).reshape(len(Eraw),6,-1)
    return measure(q,h,order,order_z)[0],mu,result

def local_system(q,h,conservative=True):
    p,w,J,mu,plane_mu=measure(q,h);_,_,B=raw(q,p,h*p[:,2]/2)
    _,_,R=project_fields(q,h,B);pn,wn=native_volume();_,Jn,Bn=raw(q,pn,h*pn[:,2]/2)
    return p,w,J,B,R,pn,wn,Jn,Bn

def dual_force(q,h,Bfull,Bmid,tau,order=9,order_z=5,state=None):
    state=prepare(q,order) if state is None else state
    p,w,J,mu,plane_mu=measure(q,h,order,order_z)
    avg=np.einsum('pz,pzk->pk',mu.reshape(order*order,order_z),tau.reshape(order*order,order_z,6))/plane_mu[:,None]
    projected=project_mid(state,h,np.einsum('ij,pj->pi',CI,avg)[:,:,None],order_z)[0][:,:,0]@C.T
    return np.einsum('p,pki,pk->i',mu,Bfull,tau)+np.einsum('p,pki,pk->i',plane_mu,Bmid,projected-avg)

def sampled_expansion(q,points,conservative=True):
    order=int(np.sqrt(len(points)));state=prepare(q,order)
    if not np.allclose(state['p'],points,rtol=0,atol=1e-14):raise ValueError('quadrature_points_required')
    J,B0,B1=expansion(q,points);P,mu,H=project_mid(state,0.,B0)
    return J,P,B1

# Same algebraic energy/force/tangent assembly as the preceding explicitly
# differentiated projection, with this module's reference-fixed projector.
def nonlinear(q,qcur,h,v1,v2,conservative=True):
    p,w,J,B,R,pn,wn,Jn,Bn=local_system(q,h,conservative)
    def data(points):
        _,g,_=tables(points,h*points[:,2]/2);J0=np.einsum('na,pnb->pab',q.reshape(75,3),g);G=g@np.linalg.inv(J0)
        F=np.eye(3)+np.einsum('na,pnb->pab',(qcur-q).reshape(75,3),G)
        E=np.einsum('kij,pij->pk',MB,(F.transpose(0,2,1)@F-np.eye(3))/2)
        Bcur=np.einsum('kij,pai,pnj->pkna',MB,F,G).reshape(len(points),6,225)
        d1=np.einsum('na,pnb->pab',v1.reshape(75,3),G);d2=np.einsum('na,pnb->pab',v2.reshape(75,3),G)
        second=np.einsum('kij,pij->pk',MB,(d1.transpose(0,2,1)@d2+d2.transpose(0,2,1)@d1)/2)
        return E,Bcur,second
    e,b,d2=data(p);en,bn,d2n=data(pn)
    _,mu,er=project_fields(q,h,e[:,:,None],en[:,:,None]);er=er[:,:,0]
    _,_,br=project_fields(q,h,b,bn);_,_,d2r=project_fields(q,h,d2[:,:,None],d2n[:,:,None])
    stress=er@C.T;energy=np.einsum('p,pk,pk->',mu,er,stress)/2;force=np.einsum('p,pki,pk->i',mu,br,stress)
    tangent=np.einsum('p,pk,kl,pl->',mu,br@v1,C,br@v2)+np.einsum('p,pk,pk->',mu,stress,d2r[:,:,0])
    return energy,force,tangent

def assemble(mesh,k,order,method='projected'):
    # Reuse the fieldwise assembly with this variational projection, without
    # changing any existing module globals or prior frozen source.
    return _assemble(mesh,k,order,method)


def _assemble(mesh,k,order,method='raw'):
    p,w=quadrature(order,2);free_rd=np.r_[mesh['free'][0],mesh['free'][1]];free_c=mesh['free'][2]
    rd_lookup={int(v):i for i,v in enumerate(free_rd)};c_lookup={int(v):i for i,v in enumerate(free_c)}
    rows=len(mesh['cells'])*len(p)*6;A0=np.zeros((rows,3*len(free_rd)));A1=np.zeros_like(A0);D1=np.zeros((rows,3*len(free_c)))
    targets={kind:np.zeros(rows) for kind in ['quadratic','cubic','quartic','exponential']}
    dc=np.r_[mesh['free'][1],mesh['free'][2]];dc_lookup={int(v):i for i,v in enumerate(dc)};M=np.zeros((len(dc),len(dc)));area=0.;zero_c=0.
    for cell,ids in enumerate(mesh['cells']):
        q=mesh['ref'][ids].reshape(225)
        J,B0,B1=expansion(q,p) if method=='raw' else sampled_expansion(q,p,method=='conservative')
        weight=np.sqrt(w*np.linalg.det(J));sl=slice(cell*len(p)*6,(cell+1)*len(p)*6)
        W0=np.einsum('ij,pjn->pin',CH,B0)*weight[:,None,None];W1=np.einsum('ij,pjn->pin',CH,B1)*weight[:,None,None]
        zero_c=max(zero_c,float(np.linalg.norm(B0[:,:,150:])))
        for a,node in enumerate(ids):
            if int(node) in rd_lookup:
                j=rd_lookup[int(node)];A0[sl,3*j:3*j+3]=W0[:,:,3*a:3*a+3].reshape(-1,3);A1[sl,3*j:3*j+3]=W1[:,:,3*a:3*a+3].reshape(-1,3)
            elif int(node) in c_lookup:
                j=c_lookup[int(node)];D1[sl,3*j:3*j+3]=W1[:,:,3*a:3*a+3].reshape(-1,3)
        Nr,gr=shape(p,0);Jsurf=np.einsum('na,pnb->pab',mesh['ref'][ids[:25]],gr);G=Jsurf.transpose(0,2,1)@Jsurf;aw=w*np.sqrt(np.linalg.det(G));area+=aw.sum()
        for field in [1,2]:
            N,g=shape(p,field);local=np.einsum('p,pi,pj->ij',aw,N,N)+np.einsum('p,pia,pab,pjb->ij',aw,g,np.linalg.inv(G),g)
            nodes=ids[SLICES[field]];keep=[a for a,node in enumerate(nodes) if int(node) in dc_lookup];where=[dc_lookup[int(nodes[a])] for a in keep]
            M[np.ix_(where,where)]+=local[np.ix_(keep,keep)]
        x=(Nr@mesh['ref'][ids[:25]])[:,0]
        for kind in targets:targets[kind][sl]=(target(kind,k,x)@CH.T*weight[:,None]).reshape(-1)
    return dict(A0=A0,A1=A1,D1=D1,targets=targets,M=M/area,area=area,free_rd=free_rd,free_c=free_c,zero_c=zero_c)

